import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
await fs.mkdir('qa',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
const url=process.env.PREVIEW_URL??'http://127.0.0.1:4186';
await page.goto(url,{waitUntil:'networkidle'});
await page.locator('#map-loading').waitFor({state:'hidden',timeout:30000});
assert.equal(await page.locator('.district-row').count(),26);
await page.waitForTimeout(800);
const mapBox=await page.locator('#map').boundingBox();
await page.mouse.click(mapBox.x+mapBox.width/2,mapBox.y+mapBox.height/2);
await page.getByRole('button',{name:'Return to state overview'}).waitFor({state:'visible'});
await page.locator('#clear-selection').click();
await page.screenshot({path:'qa/desktop.png',fullPage:true});
await page.locator('#election').selectOption({label:'2022 governor'});
assert.equal(await page.locator('#map-election-name').textContent(),'2022 governor');
await page.locator('.district-row').first().click();
await page.getByRole('button',{name:'Return to state overview'}).waitFor({state:'visible'});
await page.getByRole('button',{name:'Population',exact:true}).click();
await page.getByRole('button',{name:'View audit'}).click();
assert.equal(await page.locator('dialog[open]').count(),1);
assert.match(await page.locator('#dialog-body').textContent(),/island/);
await page.getByRole('button',{name:'Close dialog'}).click();
await page.locator('#plan').selectOption('reference');
await page.waitForFunction(()=>document.querySelector('#map-plan-name').textContent==='2024 adopted map');
assert.equal(await page.locator('.district-row').count(),26);
const unitsResponse=page.waitForResponse(r=>r.url().includes('voting-units.geojson')&&r.status()===200);
await page.locator('#units').check();
await unitsResponse;
await page.waitForTimeout(1000);
await page.locator('#units').uncheck();
await page.locator('#swing').fill('3');
assert.match(await page.locator('#swing-caption').textContent(),/\+3.0/);
await page.locator('#reset-swing').click();
assert.equal(await page.locator('#swing').inputValue(),'0');
await page.locator('#plan').selectOption('stress');
await page.waitForFunction(()=>document.querySelector('#map-plan-name').textContent==='Historical stress search');
assert.equal(await page.locator('.district-row').count(),26);
await page.locator('#plan').selectOption('candidate');
await page.waitForFunction(()=>document.querySelector('#map-plan-name').textContent==='2024 sweep');
await page.locator('#election').selectOption({label:'2024 president'});
assert.equal(await page.locator('#dem-seats').textContent(),'26');
await page.getByRole('button',{name:'Vote margin',exact:true}).click();
await page.setViewportSize({width:390,height:844});
await page.locator('#fit-map').click();
await page.waitForTimeout(1000);
await page.locator('#notice').waitFor({state:'hidden',timeout:7000});
await page.screenshot({path:'qa/mobile.png',fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'Mobile has horizontal overflow');
await page.getByRole('button',{name:'Sources & credits',exact:true}).click();
assert.match(await page.locator('#dialog-body').textContent(),/New York Times/);
await page.getByRole('button',{name:'Close dialog'}).click();
console.log(JSON.stringify({errors,districts:26,checks:['desktop map','district selection','13-election selector','plan switch','population coloring','audit dialog','voting unit overlay','swing scenario','mobile layout','public credits']},null,2));
await browser.close();
assert.deepEqual(errors,[]);
